// Renders the generated Python client (conductor_client.py) from the tool
// registry: stdlib only, one keyword-only method per tool, a functional
// TypedDict per named object. Contract: docs/mcp-applications.md → Client libraries.

import { buildClientModel, pyParamName, type ClientToolSpec, type Declaration, type Param, type ToolModel, type TypeNode } from './typeModel.ts';

function pyLiteral(v: string | number | boolean | null): string {
  if (v === null) return 'None';
  if (v === true) return 'True';
  if (v === false) return 'False';
  return JSON.stringify(v);
}

function pyType(t: TypeNode): string {
  switch (t.kind) {
    case 'str': return 'str';
    case 'int': return 'int';
    case 'num': return 'float';
    case 'bool': return 'bool';
    case 'null': return 'None';
    case 'any': return 'Any';
    case 'lit': return t.value === null ? 'None' : `Literal[${pyLiteral(t.value)}]`;
    case 'list': return `list[${pyType(t.item)}]`;
    case 'map': return `dict[str, ${pyType(t.value)}]`;
    case 'ref': return t.name;
    case 'union': {
      // Consecutive non-null literals share one Literal[...].
      const parts: string[] = [];
      let lits: string[] = [];
      const flush = () => { if (lits.length) parts.push(`Literal[${lits.join(', ')}]`); lits = []; };
      for (const m of t.members) {
        if (m.kind === 'lit' && m.value !== null) { lits.push(pyLiteral(m.value)); continue; }
        flush();
        parts.push(pyType(m));
      }
      flush();
      return parts.join(' | ');
    }
  }
}

function comment(text: string, indent: string): string[] {
  return text.split('\n').map(l => (l ? `${indent}# ${l}` : `${indent}#`));
}

function docEscape(s: string): string {
  return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function renderDeclaration(d: Declaration): string {
  if (d.kind === 'alias') return `${d.name} = ${pyType(d.type)}\n`;
  if (!d.fields.length) return `${d.name} = TypedDict(${JSON.stringify(d.name)}, {})\n`;
  const lines = [`${d.name} = TypedDict(${JSON.stringify(d.name)}, {`];
  for (const f of d.fields) {
    if (f.description) lines.push(...comment(f.description, '    '));
    const t = pyType(f.type);
    lines.push(`    ${JSON.stringify(f.key)}: ${f.optional ? `NotRequired[${t}]` : t},`);
  }
  lines.push('})');
  return lines.join('\n') + '\n';
}

function paramDoc(p: Param): string {
  const parts = [p.description ?? ''];
  if (p.hasDefault) parts.push(`(default: ${JSON.stringify(p.default)})`);
  return parts.filter(Boolean).join(' ');
}

function renderMethod(t: ToolModel): string {
  const sig = ['self'];
  if (t.params.length) {
    sig.push('*');
    for (const p of t.params) sig.push(`${pyParamName(p.key)}: ${pyType(p.type)}${p.optional ? ' = _OMIT' : ''}`);
  }
  const lines = [`    def ${t.name}(${sig.join(', ')}) -> ${t.resultName}:`];
  const [head, ...body] = docEscape(t.description).split('\n');
  const doc = [`        """${head}`, ...body.map(l => (l ? `        ${l}` : ''))];
  if (t.params.length) {
    doc.push('', '        Args:');
    for (const p of t.params) {
      const [first, ...rest] = docEscape(paramDoc(p)).split('\n');
      doc.push(`            ${pyParamName(p.key)}: ${first}`.trimEnd(), ...rest.map(l => (l ? `                ${l}` : '')));
    }
  }
  doc.push('        """');
  lines.push(...doc);
  const wire = t.params.map(p => `'${p.key}': ${pyParamName(p.key)}`).join(', ');
  lines.push(`        return self.call('${t.name}', _args({${wire}}))`);
  return lines.join('\n') + '\n';
}

const HEADER = `# conductor_client.py — a typed client for code-conductor's /mcp server.
#
# Generated by code-conductor from its MCP tool registry at every boot; do not
# edit: the file is overwritten. Needs Python 3.11+ and the standard library
# only. Contract: docs/mcp-applications.md → Client libraries.
import sys

if sys.version_info < (3, 11):
    raise ImportError('conductor_client needs Python 3.11 or newer')

import json
import os
import urllib.error
import urllib.parse
import urllib.request
from typing import Any, Literal, NotRequired, TypedDict

DEFAULT_URL = 'http://127.0.0.1:8787/mcp'

# cc listens on loopback: an inherited http_proxy must not route to it.
_OPENER = urllib.request.build_opener(urllib.request.ProxyHandler({}))

# An omitted argument: never sent, unlike None, which is sent as null.
_OMIT: Any = object()


def _args(d: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in d.items() if v is not _OMIT}


class ConductorError(Exception):
    """A refusal or a fault from cc.

    status is the HTTP status: 200 for a tool's own refusal, 4xx/5xx for a
    protocol fault. code is None when the response was not JSON.
    """

    def __init__(self, code: str | None, reason: str, status: int, body: Any):
        super().__init__(f"{code}: {reason} (HTTP {status})")
        self.code = code
        self.reason = reason
        self.status = status
        self.body = body
`;

const CALL = `

class ConductorClient:
    """One cc /mcp endpoint. Calls are attributed to the session the URL names."""

    def __init__(self, url: str | None = None):
        self.url = (url or os.environ.get('CONDUCTOR_MCP_URL') or DEFAULT_URL).rstrip('/')

    def call(self, name: str, args: dict[str, Any] | None = None) -> Any:
        """Call any tool by name, plugin tools included; returns the parsed JSON body."""
        req = urllib.request.Request(
            f"{self.url}/tools/{urllib.parse.quote(name, safe='')}",
            data=json.dumps({} if args is None else args).encode('utf-8'),
            headers={'content-type': 'application/json'},
            method='POST',
        )
        try:
            with _OPENER.open(req) as res:
                status, text = res.status, res.read().decode('utf-8')
        except urllib.error.HTTPError as e:
            status, text = e.code, e.read().decode('utf-8')
        try:
            body = json.loads(text)
        except ValueError:
            raise ConductorError(None, 'response is not JSON', status, text) from None
        if status >= 400 or (isinstance(body, dict) and body.get('ok') is False):
            obj = body if isinstance(body, dict) else {}
            raise ConductorError(obj.get('code'), obj.get('reason', f'HTTP {status}'), status, body)
        return body
`;

export function renderPythonClient(tools: ClientToolSpec[]): string {
  const model = buildClientModel(tools);
  const decls = model.declarations.map(renderDeclaration).join('\n');
  const methods = model.tools.map(renderMethod).join('\n');
  return `${HEADER}\n\n${decls}${CALL}\n${methods}`;
}
