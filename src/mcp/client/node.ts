// Renders the generated Node client (conductor_client.mjs) from the tool
// registry: global fetch only, one method per tool taking one arguments
// object, a JSDoc typedef per named object. Contract:
// docs/mcp-applications.md → Client libraries.

import { buildClientModel, type ClientToolSpec, type Declaration, type Param, type ToolModel, type TypeNode } from './typeModel.ts';

function jsType(t: TypeNode): string {
  switch (t.kind) {
    case 'str': return 'string';
    case 'int':
    case 'num': return 'number';
    case 'bool': return 'boolean';
    case 'null': return 'null';
    case 'any': return '*';
    case 'lit': return JSON.stringify(t.value);
    case 'list': return `Array<${jsType(t.item)}>`;
    case 'map': return `Object<string, ${jsType(t.value)}>`;
    case 'ref': return t.name;
    case 'union': return `(${t.members.map(jsType).join('|')})`;
  }
}

// Comment text, safe inside /** … */, one ` * `-prefixed line per input line.
function docLines(text: string, indent: string, lead = ''): string[] {
  return text.replace(/\*\//g, '*\\/').split('\n').map((l, i) => {
    const body = i === 0 ? lead + l : l;
    return body ? `${indent} * ${body}` : `${indent} *`;
  });
}

function renderDeclaration(d: Declaration): string {
  if (d.kind === 'alias') return `/** @typedef {${jsType(d.type)}} ${d.name} */\n`;
  const lines = ['/**', ` * @typedef {Object} ${d.name}`];
  for (const f of d.fields) {
    const key = f.optional ? `[${f.key}]` : f.key;
    lines.push(...docLines(f.description ?? '', '', `@property {${jsType(f.type)}} ${key}${f.description ? ' - ' : ''}`));
  }
  lines.push(' */');
  return lines.join('\n') + '\n';
}

function paramDoc(p: Param): string {
  const parts = [p.description ?? ''];
  if (p.hasDefault) parts.push(`(default: ${JSON.stringify(p.default)})`);
  return parts.filter(Boolean).join(' ');
}

function renderMethod(t: ToolModel): string {
  const anyRequired = t.params.some(p => !p.optional);
  const lines = ['  /**', ...docLines(t.description, '  '), '   *', `   * @param {Object} ${anyRequired ? 'args' : '[args]'}`];
  for (const p of t.params) {
    const name = p.optional ? `[args.${p.key}]` : `args.${p.key}`;
    const doc = paramDoc(p);
    lines.push(...docLines(doc, '  ', `@param {${jsType(p.type)}} ${name}${doc ? ' - ' : ''}`));
  }
  lines.push(`   * @returns {Promise<${t.resultName}>}`, '   */');
  lines.push(`  ${t.name}(${anyRequired ? 'args' : 'args = {}'}) {`, `    return this.call('${t.name}', args);`, '  }');
  return lines.join('\n') + '\n';
}

const HEADER = `// conductor_client.mjs — a typed client for code-conductor's /mcp server.
//
// Generated by code-conductor from its MCP tool registry at every boot; do not
// edit: the file is overwritten. Needs Node 18+ (global fetch) and nothing
// else. Contract: docs/mcp-applications.md → Client libraries.

if (typeof fetch !== 'function') throw new Error('conductor_client.mjs needs Node 18 or newer (global fetch)');

export const DEFAULT_URL = 'http://127.0.0.1:8787/mcp';

/**
 * A refusal or a fault from cc. \`status\` is the HTTP status: 200 for a tool's
 * own refusal, 4xx/5xx for a protocol fault. \`code\` is null when the response
 * was not JSON.
 */
export class ConductorError extends Error {
  /**
   * @param {string|null} code
   * @param {string} reason
   * @param {number} status
   * @param {*} body
   */
  constructor(code, reason, status, body) {
    super(\`\${code}: \${reason} (HTTP \${status})\`);
    this.name = 'ConductorError';
    this.code = code;
    this.reason = reason;
    this.status = status;
    this.body = body;
  }
}
`;

const CLIENT_HEAD = `
/** One cc /mcp endpoint. Calls are attributed to the session the URL names. */
export class ConductorClient {
  /** @param {string} [url] */
  constructor(url) {
    this.url = (url || process.env.CONDUCTOR_MCP_URL || DEFAULT_URL).replace(/\\/+$/, '');
  }

  /**
   * Call any tool by name, plugin tools included; resolves to the parsed JSON body.
   * @param {string} name
   * @param {Object<string, *>} [args]
   * @returns {Promise<*>}
   */
  async call(name, args = {}) {
    const res = await fetch(\`\${this.url}/tools/\${encodeURIComponent(name)}\`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify(args),
    });
    const text = await res.text();
    let body;
    try { body = JSON.parse(text); }
    catch { throw new ConductorError(null, 'response is not JSON', res.status, text); }
    const obj = body !== null && typeof body === 'object' && !Array.isArray(body) ? body : null;
    if (res.status >= 400 || obj?.ok === false) {
      throw new ConductorError(obj?.code ?? null, obj?.reason ?? \`HTTP \${res.status}\`, res.status, body);
    }
    return body;
  }
`;

export function renderNodeClient(tools: ClientToolSpec[]): string {
  const model = buildClientModel(tools);
  const decls = model.declarations.map(renderDeclaration).join('\n');
  const methods = model.tools.map(renderMethod).join('\n');
  return `${HEADER}\n${decls}${CLIENT_HEAD}\n${methods}}\n`;
}
