static void pins_load(const char *file)
{
	FILE *f = fopen(file, "r");
	char  line[PATH_MAX + 64];

	if (!f) {
		fprintf(stderr, "cc-union: pins %s: %s\n", file, strerror(errno));
		exit(1);
	}
	while (fgets(line, sizeof(line), f))
		if (pins_parse_line(line) != 0) {
			fprintf(stderr, "cc-union: pins: %s\n", policy_err);
			exit(1);
		}
	fclose(f);
}

int main(int argc, char *argv[])
{
	const char *hr = getenv("CC_UNION_HOST_ROOT") ?: "/";
	const char *rr = getenv("CC_UNION_REMOTE");
	const char *pf = getenv("CC_UNION_PINS");
	const char *mp = getenv("CC_UNION_MNT");
	const char *tp = getenv("CC_UNION_TRACE");
	const char *fp = getenv("CC_UNION_REFUSALS");
	int probe;

	self_tgid     = getpid();
	mark_path     = getenv("CC_UNION_MARK_PATH");
	control_path  = getenv("CC_UNION_CONTROL");

	if (!rr || !pf) {
		fprintf(stderr, "cc-union: REFUSED — CC_UNION_REMOTE and "
				"CC_UNION_PINS are both required\n");
		return 1;
	}
	/*
	 * THE MARK IS THE PROJECT TIER'S ONLY KEY. Without the marking event
	 * every caller is unmarked and the remote tier is unreachable, so the
	 * mount would serve a silent host-only filesystem that looks exactly
	 * like a containment success. Refuse instead.
	 */
	if (!mark_path) {
		fprintf(stderr, "cc-union: REFUSED — CC_UNION_MARK_PATH is required; "
				"without it no caller is ever marked and the project tier "
				"is unreachable\n");
		return 1;
	}
	/* Same reasoning for the channel: a daemon that cannot reach cc can
	 * materialise nothing, so every project path would answer -EIO. */
	if (!control_path) {
		fprintf(stderr, "cc-union: REFUSED — CC_UNION_CONTROL is required; "
				"without cc's control socket no remote path can be "
				"materialised\n");
		return 1;
	}
	if (pthread_key_create(&control_key, control_close) != 0) {
		fprintf(stderr, "cc-union: REFUSED — could not create the control-socket key\n");
		return 1;
	}
	/* Connect once BEFORE mounting. An unconnectable socket discovered on
	 * the first getattr is a mount that came up and answers nothing. */
	if ((probe = control_connect()) < 0) {
		fprintf(stderr, "cc-union: REFUSED — cannot connect to cc's control "
				"socket at %s: %s\n", control_path, strerror(errno));
		return 1;
	}
	close(probe);
	ccu_xport.roundtrip = control_roundtrip;

	snprintf(host_root,   sizeof(host_root),   "%s", hr);
	snprintf(remote_root, sizeof(remote_root), "%s", rr);

	pins_load(pf);
	/* The mountpoint lies inside BOTH roots, so an unguarded union recurses
	 * forever the first time anything walks the tree. S1 §7.5. */
	if (mp && pin_add(T_HIDE, mp) != 0) {
		fprintf(stderr, "cc-union: REFUSED — %s\n", policy_err);
		return 1;
	}
	/* AFTER every pin is in: the ancestor set is derived from the final
	 * table, so the mountpoint's own parents are synthetic too. */
	anc_build();

	if ((host_fd = open(host_root, O_PATH | O_DIRECTORY)) == -1) {
		fprintf(stderr, "cc-union: host root %s: %s\n",
			host_root, strerror(errno));
		return 1;
	}
	if ((remote_fd = open(remote_root, O_PATH | O_DIRECTORY)) == -1) {
		fprintf(stderr, "cc-union: mirror %s: %s\n",
			remote_root, strerror(errno));
		return 1;
	}
	if (tp) {
		if (!(trace_fp = fopen(tp, "a"))) {
			fprintf(stderr, "cc-union: trace %s: %s\n", tp, strerror(errno));
			return 1;
		}
		setvbuf(trace_fp, NULL, _IOLBF, 0);
	}
	if (fp) {
		if (!(refusal_fp = fopen(fp, "a"))) {
			fprintf(stderr, "cc-union: refusal log %s: %s\n", fp, strerror(errno));
			return 1;
		}
		setvbuf(refusal_fp, NULL, _IOLBF, 0);
	}

	fprintf(stderr, "cc-union: host=%s mirror=%s pins=%zu synth=%zu "
		"markpath=%s control=%s tgid=%d\n",
		host_root, remote_root, npins, nancs, mark_path, control_path,
		(int)self_tgid);

	umask(0);
	return fuse_main(argc, argv, &pt_ops, NULL);
}
