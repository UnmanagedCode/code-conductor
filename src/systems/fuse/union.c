/*
 * union.c — the FUSE-union daemon cc mounts under a remote-backed worker.
 *
 * ONE POLICY, NOT A MEASUREMENT INSTRUMENT. This file is a fork of the frozen
 * S3 spike instrument `rig/fuse-union-s3.c`, which had three selectable routing
 * modes and eight knobs because its job was to compare them. Every knob is
 * gone; what is left is the single policy the epic specifies. PROVENANCE.md
 * carries the fork point and one row per intentional divergence.
 *
 * ── what it serves, and to whom ─────────────────────────────────────────────
 *
 * A longest-prefix tier table, loaded from $CC_UNION_PINS and generated by
 * src/systems/fuse/tierTable.ts. Five classes reach this file; a sixth is
 * derived (policy.h).
 *
 * IT IS READ THROUGH ONE OF TWO VIEWS (policy.h's `enum view`, card 2026-0398).
 * `VIEW_CLI` is the table as written, and only the MARKED CLI resolves against
 * it. `VIEW_HOST` is everyone else's: the `project` pins are struck and the
 * ancestor table is not consulted, so an unmarked caller is served the
 * orchestrator's own filesystem wherever it has something and a traverse-only
 * overlay node at the cwd components it has not. The unmarked answer is
 * therefore the SAME AT EVERY `mirrorRoot`, which is the property the card
 * bought; the classes below describe `VIEW_CLI`.
 *
 *   host     the orchestrator's own filesystem, always, for marked and unmarked
 *            callers alike. The CLI's execution closure lives here: its binary,
 *            ld-linux and its shared objects, $HOME, the session scratch dir,
 *            the specific /etc files the runtime needs.
 *   project  the remote tier; its bytes reach a caller marked as the CLI and no
 *            other, and THAT IS NOW STRUCTURAL: the pins are absent from
 *            `VIEW_HOST`, so an unmarked resolution cannot produce this tier,
 *            cannot send a control frame and cannot read the mirror. Such a
 *            path resolves in `VIEW_HOST` instead — to a shorter host or bind
 *            pin, to `hide` (striking a `project` pin hands the longest-prefix
 *            contest to whatever shorter pin covers the path, and a `hide` pin
 *            is eligible to win it: hidden stays hidden), to `fail` (and `fail`
 *            means host), or to the overlay node.
 *   bind     a directory bootstrap.sh mounts the ORCHESTRATOR's own over, after
 *            the union is up. Served here as a read-only synthetic node purely
 *            so the bind target exists — /proc, /sys, /dev must never be tiers
 *            (S1 §7.1: a passthrough serving /proc/self/exe answers with the
 *            DAEMON's identity and breaks a bun single-file executable).
 *   hide     ENOENT, and suppressed from the parent's readdir. The union's own
 *            scaffolding, which it must not serve through itself.
 *   fail     ENOENT on both sides FOR THE MARKED CLI, because the system's
 *            advertisement excluded it or no pin covers it. Also refused at
 *            cc's file-tool seam, so it fails both surfaces. For an UNMARKED
 *            caller it is substituted to `host` UNCONDITIONALLY
 *            (policy_caller_tier, policy.h) and a `served/unmarked-host-served`
 *            row names the path. Unconditional because `fail` is a statement
 *            about cc's pin list rather than about a caller that was never going
 *            to be served the remote.
 *   synth    DERIVED, never written in the pins file. In `VIEW_CLI` it is the
 *            ancestors of every pin, so a pinned leaf is reachable without its
 *            parents being served from anywhere. In `VIEW_HOST` the ancestor
 *            table is not consulted at all — a scaffold node over a directory
 *            the orchestrator HAS would subtract it — and the enumerator carries
 *            the OVERLAY instead: a traverse-only node at a cwd component the
 *            orchestrator lacks, because `chdir` needs a node there and a floor
 *            cannot put a mode on a directory that does not exist. Read-only,
 *            fixed attributes, both ways.
 *
 * AN UNMATCHED PATH IS `fail`, because T_FAIL is enum index 0 and tier_of
 * returns index 0 for a path no pin matches. The instrument's index 0 was
 * remote-first with a host fallback; that fallback is the "one path, two
 * answers" this architecture exists to remove, and deleting it is why the
 * event log below is the instrument the pin list is derived from.
 *
 * THE `fail` → `host` SUBSTITUTION FOR AN UNMARKED CALLER IS NOT THAT FALLBACK
 * COMING BACK, and the difference is mechanical rather than a matter of degree:
 * it is host-ONLY, keyed on the CALLER and never on the outcome, deterministic,
 * and it fires at exactly one tier. Nothing is tried and then retried
 * elsewhere; at `fail` the marked side has no answer at all, so there is no
 * second answer for one path to have. Which side served an op is always
 * knowable — from the trace's `tier=`/`mark=` columns, and by name from the
 * event log.
 *
 * ── the caller mark ─────────────────────────────────────────────────────────
 *
 * A thread group is marked the first time it resolves $CC_UNION_MARK_PATH — the
 * CLI's own binary. The mark is sticky, survives exec, is keyed on the TGID and
 * is revalidated against /proc field 22 on every check so a recycled pid cannot
 * inherit it. THE MARK SELECTS THE VIEW, and that is the whole of what it does
 * for routing: marked resolves `VIEW_CLI`, everyone else `VIEW_HOST`. An
 * unmarked caller therefore never names the remote at any path — no exemption,
 * no allow-list, no traversal bound to get right. Host-pinned and bind-mounted
 * paths are served to marked and unmarked callers alike, and an unmarked caller
 * at `fail` is served the host. policy.h states the ordering.
 *
 * ── the control channel ─────────────────────────────────────────────────────
 *
 * A unix stream socket at $CC_UNION_CONTROL, one connection per FUSE worker
 * thread, control frames only and never file content (policy.h's codec). No
 * remote-tier op touches the mirror before cc has answered: a bare local stat
 * would report ENOENT for a file that exists remotely and is simply not
 * materialised yet. A wedged cc becomes -EIO on a bounded receive timeout, not
 * an unkillable D state — and never a host fallback, which would look exactly
 * like a containment success.
 *
 * ── zero kernel caching ─────────────────────────────────────────────────────
 *
 * cfg->kernel_cache = 0 here, and attr_timeout/entry_timeout/negative_timeout
 * are all 0 in the mount options cc passes (src/systems/fuse/plan.ts). FUSE's
 * attribute cache is per-inode and this filesystem answers per-caller, so one
 * path measurably answered 15 bytes to `stat` and 33 to `cat` across the
 * routing boundary. policy.h's resolution cache is the caller-aware
 * replacement.
 *
 * ── carried from S1, unchanged ──────────────────────────────────────────────
 *
 * Per-request setfsuid/setfsgid is mandatory, not a tuning knob: S1 §7.2
 * measured that without it the CLI's own Bash tool fails EACCES, because its
 * scratch directory gets created root-owned. Known limit, carried:
 * supplementary groups are NOT switched (setgroups(2) is per-process, not
 * per-thread), so a caller whose access depends on one can be wrongly denied by
 * the daemon-side check. default_permissions means the kernel has already
 * checked the caller's full credentials first, so this is a second gate rather
 * than the only one. It is not equivalent.
 *
 * The self-recursion guard is a LIVENESS precondition, not a routing policy: a
 * caller in the daemon's own thread group must never be served through the
 * remote path, or the daemon blocks on a request only it can answer. Keyed on
 * one tgid, because ancestry — the only key that could describe "the CLI and
 * its children" — is unknowable exactly when it matters (S1 §6 Q2).
 *
 * The trace and the event log record PATHS ONLY, never content, so a
 * credential path may appear in them and a credential never does.
 *
 * ── known limit, recorded rather than defended against ──────────────────────
 *
 * A readdir of a `project` directory lists the mirror's children only, so a
 * host pin NESTED inside a project prefix is reachable by name but absent from
 * its parent's listing. It cannot arise at the default mirror root (the
 * project's own remote path); it can at an advertised root of "/". The event
 * log is the instrument that would surface it.
 *
 * ── environment ─────────────────────────────────────────────────────────────
 *
 *   CC_UNION_HOST_ROOT   host tier root                       (default "/")
 *   CC_UNION_REMOTE      the per-session mirror directory     (required)
 *   CC_UNION_PINS        the tier table file                  (required)
 *   CC_UNION_CONTROL     cc's control socket                  (required)
 *   CC_UNION_MARK_PATH   the path whose resolution marks a thread group
 *                                                             (required)
 *   CC_UNION_CWD         the CLI's cwd INSIDE the chroot, normalised — the
 *                        chain the floor and the overlay act on (required)
 *   CC_UNION_MNT         the mountpoint, hidden implicitly (recursion guard)
 *   CC_UNION_TRACE       every path the kernel asks about, with caller identity
 *   CC_UNION_EVENTS      the policy event log — a `#` header line, then
 *                        <kind>\t<op>\t<path>\t<reason>\t<pid>\t<tgid>\t
 *                        <comm>\t<cmdline>. The instrument the pin list is
 *                        derived from, and the channel whose `deny` rows must
 *                        be empty by the end. Path, comm and cmdline are
 *                        `policy_escape`d; identity is sampled at POLICY TIME.
 */
