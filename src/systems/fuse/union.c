/* ── caller identity, for the trace ─────────────────────────────────────── */
/*
 * pid -> (tgid, ppid, starttime, exe, cmdline), cached; a thread's tgid is
 * fixed for its life. comm is NOT cached and never will be: S1 §8.2 defect 2
 * cached it and every request from the CLI came back labelled comm=bash,
 * because the pid was first seen as the shell that later exec'd into the CLI.
 *
 * TGID AND STARTTIME COME FROM policy.h's READER, not from a second parse here:
 * the policy routes on them and the trace attributes on them, and two readers
 * of /proc for one fact is how they come to disagree.
 */
#define PCACHE_SLOTS 8192
struct pent {
	pid_t         pid, tgid, ppid;
	unsigned long long start;   /* /proc/<pid>/stat field 22 */
	char          exe[192];     /* resolved once, per pid */
	char          cmd[192];     /* full cmdline, NULs -> spaces */
};
static struct pent     pcache[PCACHE_SLOTS];
static pthread_mutex_t pcache_mu = PTHREAD_MUTEX_INITIALIZER;

static void read_exe(pid_t pid, char *out, size_t n)
{
	char buf[64];
	ssize_t r;

	snprintf(buf, sizeof(buf), "/proc/%d/exe", (int)pid);
	if ((r = readlink(buf, out, n - 1)) > 0) {
		out[r] = '\0';
		return;
	}
	/*
	 * /proc/<tgid>/exe is rendered by d_path against the READER's root. The
	 * daemon lives outside the chroot the callers live in, so the link can
	 * come back unreachable; the trace records "<unreadable>" rather than
	 * silently substituting the cmdline, because a column that means two
	 * different things in one file is worse than a gap.
	 */
	snprintf(out, n, "<unreadable>");
}

/*
 * THE COLUMN THAT ACTUALLY ATTRIBUTES AN OP. exe is the INTERPRETER for
 * anything script-shaped: a PreToolUse hook and the Bash forwarder are both
 * /bin/bash, and telling them apart is the entire containment question. The
 * kernel builds argv for a shebang script as [interpreter, script, args...],
 * so the script's own path is in the cmdline and nowhere else.
 */
static void read_cmdline(pid_t pid, char *out, size_t n)
{
	char buf[64];
	int f;
	ssize_t k, i;

	snprintf(out, n, "<gone>");
	snprintf(buf, sizeof(buf), "/proc/%d/cmdline", (int)pid);
	if ((f = open(buf, O_RDONLY)) == -1)
		return;
	k = read(f, out, n - 1);
	close(f);
	if (k <= 0) {
		snprintf(out, n, "<gone>");
		return;
	}
	out[k] = '\0';
	/*
	 * NULs become spaces -- and so does EVERY other control character. A
	 * `bash -c` cmdline carries the whole script, newlines included, and an
	 * embedded newline splits one trace row into many: the first version of
	 * this instrument produced 1662 unparsable rows out of ~3000 for exactly
	 * that reason, and the analysis silently dropped them.
	 */
	for (i = 0; i < k; i++)
		if ((unsigned char)out[i] < 0x20 || (unsigned char)out[i] == 0x7f)
			out[i] = ' ';
	while (k > 0 && out[k - 1] == ' ')
		out[--k] = '\0';
}

/*
 * Resolve TID -> (TGID, PPID, starttime, exe, cmdline). The entry is
 * REVALIDATED on every hit, unconditionally: the instrument made that a flag so
 * the cost could be measured, and the unvalidated arm was the unsound half. A
 * recycled pid otherwise returns its predecessor's tgid for the life of the
 * daemon, and exec(2) replaces the cmdline and the exe link while leaving pid,
 * tgid and start time untouched — so both the start-time compare and the
 * re-read below are load-bearing, and neither can substitute for the other.
 */
static void resolve_ids(pid_t pid, pid_t *tgid_out, pid_t *ppid_out,
			unsigned long long *start_out, const char **exe_out,
			const char **cmd_out)
{
	size_t slot = ((size_t)pid * 2654435761u) % PCACHE_SLOTS;
	pid_t tgid = -1, ppid = -1;
	unsigned long long start = 0;
	const char *exe = "<gone>", *cmd = "<gone>";
	size_t i;

	pthread_mutex_lock(&pcache_mu);
	for (i = 0; i < 64; i++) {
		struct pent *e = &pcache[(slot + i) % PCACHE_SLOTS];
		if (e->pid == pid) {
			unsigned long long now = policy_proc.starttime(pid);
			if (now != e->start) {
				e->pid = 0;   /* recycled: refill below */
				i--;
				continue;
			}
			read_exe(e->tgid > 0 ? e->tgid : pid, e->exe, sizeof(e->exe));
			read_cmdline(e->tgid > 0 ? e->tgid : pid, e->cmd, sizeof(e->cmd));
			tgid = e->tgid; ppid = e->ppid;
			start = e->start; exe = e->exe; cmd = e->cmd;
			break;
		}
		if (e->pid == 0) {
			char buf[64];
			FILE *f;

			e->pid = pid; e->tgid = policy_proc.tgid(pid); e->ppid = -1;
			e->start = 0; e->exe[0] = '\0';
			snprintf(buf, sizeof(buf), "/proc/%d/status", (int)pid);
			if ((f = fopen(buf, "r")) != NULL) {
				char line[256];
				while (fgets(line, sizeof(line), f))
					if (strncmp(line, "PPid:", 5) == 0) {
						e->ppid = (pid_t)atoi(line + 5);
						break;
					}
				fclose(f);
			}
			e->start = policy_proc.starttime(pid);
			read_exe(e->tgid > 0 ? e->tgid : pid, e->exe, sizeof(e->exe));
			read_cmdline(e->tgid > 0 ? e->tgid : pid, e->cmd, sizeof(e->cmd));
			tgid = e->tgid; ppid = e->ppid;
			start = e->start; exe = e->exe; cmd = e->cmd;
			break;
		}
	}
	pthread_mutex_unlock(&pcache_mu);
	*tgid_out  = tgid;
	*ppid_out  = ppid;
	if (start_out) *start_out = start;
	if (exe_out)   *exe_out   = exe;
	if (cmd_out)   *cmd_out   = cmd;
}

static void read_comm(pid_t pid, char *out, size_t n)
{
	char buf[64];
	FILE *f;

	snprintf(out, n, "<gone>");
	snprintf(buf, sizeof(buf), "/proc/%d/comm", (int)pid);
	if ((f = fopen(buf, "r")) != NULL) {
		if (fgets(out, n, f)) {
			char *nl = strchr(out, '\n');
			if (nl) *nl = '\0';
		}
		fclose(f);
	}
}

/*
 * THE self-recursion guard. Not a routing policy -- a liveness precondition.
 * It is the minimum possible key (one tgid) and needs no ancestry walk. Where
 * it fires the path is served from the HOST, which is the one answer that
 * cannot re-enter this daemon.
 */
static int caller_is_self(void)
{
	const struct fuse_context *c = fuse_get_context();

	if ((pid_t)c->pid == self_tgid)
		return 1;
	return policy_proc.tgid((pid_t)c->pid) == self_tgid;
}

/* THE MARKING EVENT, on every routed path. S1 §9.1 measured that this is NOT
 * the marked process's first op: it is the shell that later execs into the CLI,
 * and it does real work first. That window is a property of the launcher. */
static void mark_maybe(const char *path)
{
	if (!mark_path || strcmp(path, mark_path) != 0)
		return;
	policy_mark_tid((pid_t)fuse_get_context()->pid);
}

/* ── trace ──────────────────────────────────────────────────────────────── */

static FILE           *trace_fp = NULL;
static pthread_mutex_t trace_mu = PTHREAD_MUTEX_INITIALIZER;

static void tr(const char *op, const char *path, const char *tier)
{
	const struct fuse_context *ctx;
	char comm[24];
	const char *exe, *cmd;
	pid_t tgid, ppid;
	unsigned long long start;

	if (!trace_fp)
		return;
	ctx = fuse_get_context();
	resolve_ids((pid_t)ctx->pid, &tgid, &ppid, &start, &exe, &cmd);
	read_comm((pid_t)ctx->pid, comm, sizeof(comm));

	pthread_mutex_lock(&trace_mu);
	fprintf(trace_fp,
		"%s\t%s\ttier=%s pid=%d uid=%d gid=%d tgid=%d ppid=%d "
		"comm=%s mark=%d exe=%s cmd=%s\n",
		op, path, tier, (int)ctx->pid, (int)ctx->uid,
		(int)ctx->gid, (int)tgid, (int)ppid, comm, mark_of(tgid), exe, cmd);
	pthread_mutex_unlock(&trace_mu);
}

/* ── the control channel's transport ────────────────────────────────────── */
/*
 * ONE CONNECTION PER FUSE WORKER THREAD, opened lazily and held in a
 * pthread_key with a destructor, so a request never waits on another thread's
 * reply and a retired thread does not leak its fd. Blocking per request, as the
 * epic licenses.
 *
 * SO_RCVTIMEO IS THE WHOLE LIVENESS ARGUMENT: without it a cc that stops
 * answering leaves the calling thread in an uninterruptible FUSE wait, and the
 * mount can only be recovered by aborting the connection. With it the op fails
 * -EIO, the daemon logs a refusal, and teardown proceeds normally.
 */
#define CONTROL_TIMEOUT_MS 120000

static const char *control_path = NULL;
static pthread_key_t control_key;

/* Stored as fd+1, so a live fd 0 is distinguishable from "no connection" and
 * the key's destructor actually runs (pthread_setspecific(NULL) suppresses it). */
static void control_close(void *v)
{
	int fd = (int)(intptr_t)v - 1;
	if (fd >= 0)
		close(fd);
}

static int control_connect(void)
{
	struct sockaddr_un sa;
	struct timeval tv;
	int fd;

	if (!control_path || strlen(control_path) >= sizeof(sa.sun_path))
		return -1;
	if ((fd = socket(AF_UNIX, SOCK_STREAM | SOCK_CLOEXEC, 0)) == -1)
		return -1;
	memset(&sa, 0, sizeof(sa));
	sa.sun_family = AF_UNIX;
	snprintf(sa.sun_path, sizeof(sa.sun_path), "%s", control_path);
	if (connect(fd, (struct sockaddr *)&sa, sizeof(sa)) == -1) {
		close(fd);
		return -1;
	}
	tv.tv_sec  = CONTROL_TIMEOUT_MS / 1000;
	tv.tv_usec = (CONTROL_TIMEOUT_MS % 1000) * 1000;
	setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &tv, sizeof(tv));
	setsockopt(fd, SOL_SOCKET, SO_SNDTIMEO, &tv, sizeof(tv));
	return fd;
}

static int control_fd(void)
{
	int fd = (int)(intptr_t)pthread_getspecific(control_key) - 1;

	if (fd >= 0)
		return fd;
	if ((fd = control_connect()) < 0)
		return -1;
	pthread_setspecific(control_key, (void *)(intptr_t)(fd + 1));
	return fd;
}

static void control_drop(void)
{
	int fd = (int)(intptr_t)pthread_getspecific(control_key) - 1;
	if (fd >= 0)
		close(fd);
	pthread_setspecific(control_key, NULL);
}

static int io_all(int fd, void *buf, size_t n, int writing)
{
	unsigned char *p = buf;
	while (n > 0) {
		ssize_t k = writing ? write(fd, p, n) : read(fd, p, n);
		if (k > 0) { p += k; n -= (size_t)k; continue; }
		if (k == -1 && errno == EINTR) continue;
		return -1;
	}
	return 0;
}

static ssize_t control_roundtrip(void *ctx, const unsigned char *req, size_t reqlen,
				 unsigned char *rep, size_t repcap)
{
	int fd = control_fd();

	(void)ctx;
	if (fd < 0)
		return -1;
	if (repcap < CCU_REPLY_LEN)
		return -1;
	if (io_all(fd, (void *)(uintptr_t)req, reqlen, 1) != 0 ||
	    io_all(fd, rep, CCU_REPLY_LEN, 0) != 0) {
		/* A half-written request or a truncated reply leaves the stream
		 * out of frame; the only safe repair is a new connection. */
		control_drop();
		return -1;
	}
	return (ssize_t)CCU_REPLY_LEN;
}

/* ── per-request credentials (verbatim from S1; see the header) ─────────── */

static inline void cred_enter(void)
{
	const struct fuse_context *c = fuse_get_context();
	setfsgid(c->gid);
	setfsuid(c->uid);
}

static inline void cred_leave(void)
{
	setfsuid(0);
	setfsgid(0);
}

/* ── routing ────────────────────────────────────────────────────────────── */

static const char *rel(const char *path)
{
	if (path[0] == '/' && path[1] == '\0')
		return ".";
	return path + 1;
}

struct route {
	enum tier   tier;
	int         fd;
	const char *rp;
};

#define SYNTHETIC(t) ((t) == T_SYNTH || (t) == T_BIND)

/*
 * fd -> the tier its open() routed to, and whether that fd was opened for
 * writing. The tier column is the trace's; the writable bit is what makes
 * pt_release able to push a DIRTY frame for exactly the handles that could have
 * changed the file.
 *
 * A plain array indexed by fd, one byte each, written once by the open that
 * produced the fd and read by that fd's own ops. No lock: the kernel does not
 * hand the same fd number to two live handles.
 */
#define FDTIER_SLOTS 65536
static unsigned char fd_tier[FDTIER_SLOTS];
static unsigned char fd_dirty[FDTIER_SLOTS];

static void fd_tier_set(int fd, enum tier t, int writable)
{
	if (fd >= 0 && fd < FDTIER_SLOTS) {
		fd_tier[fd] = (unsigned char)t;
		fd_dirty[fd] = (unsigned char)!!writable;
	}
}

/*
 * THE ONE DISPATCH. `fop` is the control frame this op owes cc before the
 * mirror may be touched (0 for an op that owes none); `for_create` routes a
 * path that does not exist yet by its parent, exactly where the instrument did.
 *
 * There is no `default:` arm and there is no host fallback. The switch below is
 * exhaustive over `enum tier`; anything that reaches past it — T_FAIL, and any
 * member a later edit adds — fails closed and says so in the refusal log.
 */
static int route(const char *op, const char *path, int for_create, uint8_t fop,
		 struct route *r)
{
	r->rp   = rel(path);
	r->fd   = -1;
	r->tier = resolve_class(path);

	/* THE MARKING EVENT, before tier dispatch: reading the CLI's own binary
	 * is a host-tier op, so a mark set after dispatch would never fire. */
	mark_maybe(path);

	switch (r->tier) {
	case T_HIDE:
		return -ENOENT;

	case T_HOST:
		r->fd = host_fd;
		return 0;

	/* Answered by the caller from the ancestor table — there is no backing
	 * directory, which is the point: these nodes exist so a pinned leaf is
	 * reachable and a bind target exists, and nothing else. */
	case T_BIND:
	case T_SYNTH:
		return 0;

	case T_PROJECT: {
		int rc;
		if (caller_is_self()) {
			/* Liveness, not policy: the one answer that cannot
			 * re-enter this daemon. */
			r->fd = host_fd;
			policy_refuse(op, path, "self-recursion");
			return 0;
		}
		rc = policy_project_route(op, path, (pid_t)fuse_get_context()->pid, fop,
					  for_create ? CCU_FLAG_FOR_CREATE : 0);
		if (rc)
			return rc;
		r->fd = remote_fd;      /* no fallback, by design */
		return 0;
	}

	case T_FAIL:
		break;
	}
	policy_refuse(op, path, "unpinned-fail-closed");
	return -ENOENT;
}

#define ROUTE(op, p, create, fop)                       \
	struct route r;                                 \
	int rrc = route(op, p, create, fop, &r);        \
	if (rrc)                                        \
		return rrc;                             \
	tr(op, p, tier_name(r.tier));                   \
	const char *rp = r.rp;

/* ── operations ─────────────────────────────────────────────────────────── */

static void *pt_init(struct fuse_conn_info *conn, struct fuse_config *cfg)
{
	(void)conn;
	/* A union must not invent st_ino. The host root and the mirror live on
	 * the same host filesystem, so their inode spaces cannot collide;
	 * synthetic nodes supply their own from the ancestor table, in a range
	 * (SYNTH_INO_BASE) no real filesystem here hands out. */
	cfg->use_ino = 1;
	/* Criterion 7's kernel half. The mount-option half — attr_timeout,
	 * entry_timeout, negative_timeout — is cc's MOUNT_OPTS. */
	cfg->kernel_cache = 0;
	return NULL;
}

static int pt_getattr(const char *path, struct stat *st, struct fuse_file_info *fi)
{
	int rc;
	if (fi && fi->fh) {
		tr("getattr", path, "fh");
		return fstat((int)fi->fh, st) == -1 ? -errno : 0;
	}
	{
		ROUTE("getattr", path, 0, CCU_STAT);
		if (SYNTHETIC(r.tier))
			return policy_synth_getattr(path, st);
		cred_enter();
		rc = fstatat(r.fd, rp, st, AT_SYMLINK_NOFOLLOW);
		int e = errno;
		cred_leave();
		return rc == -1 ? -e : 0;
	}
}

static int pt_access(const char *path, int mask)
{
	ROUTE("access", path, 0, CCU_STAT);
	/* A synthetic node is 0555 root:root and there is nothing to widen it
	 * to: EROFS on every mutation, so a write probe is a refusal rather than
	 * a permissions question. */
	if (SYNTHETIC(r.tier))
		return (mask & W_OK) ? -EROFS : 0;
	cred_enter();
	int rc = faccessat(r.fd, rp, mask, AT_EACCESS);
	int e = errno;
	cred_leave();
	return rc == -1 ? -e : 0;
}

static int pt_readlink(const char *path, char *buf, size_t size)
{
	ROUTE("readlink", path, 0, CCU_STAT);
	if (SYNTHETIC(r.tier))
		return -EINVAL;         /* a directory is not a symlink */
	cred_enter();
	ssize_t n = readlinkat(r.fd, rp, buf, size - 1);
	int e = errno;
	cred_leave();
	if (n == -1) return -e;
	buf[n] = '\0';
	return 0;
}

/* ── readdir ────────────────────────────────────────────────────────────── */
/*
 * NO MERGE. The instrument merged the remote's listing with the host's because
 * its default tier merged their contents; with the fallback gone there is
 * exactly one source per directory, and a synthetic directory that also listed
 * the host's would be the leak criterion 3 forbids.
 */

struct dirhandle {
	DIR      *d;            /* NULL for a synthetic or bind node */
	enum tier tier;
	char      path[PATH_MAX];
};

static DIR *opendir_at(int dirfd, const char *rp)
{
	int fd = openat(dirfd, rp, O_RDONLY | O_DIRECTORY);
	DIR *d;
	if (fd == -1) return NULL;
	if (!(d = fdopendir(fd))) { int e = errno; close(fd); errno = e; }
	return d;
}

static int pt_opendir(const char *path, struct fuse_file_info *fi)
{
	ROUTE("opendir", path, 0, CCU_LIST);
	struct dirhandle *h;
	int e;

	if (!(h = calloc(1, sizeof(*h))))
		return -ENOMEM;
	snprintf(h->path, sizeof(h->path), "%s", path);
	h->tier = r.tier;

	if (SYNTHETIC(r.tier)) {
		fi->fh = (uint64_t)(uintptr_t)h;
		return 0;
	}
	cred_enter();
	h->d = opendir_at(r.fd, rp);
	e = errno;
	cred_leave();
	if (!h->d) {
		free(h);
		return -(e ? e : ENOENT);
	}
	fi->fh = (uint64_t)(uintptr_t)h;
	return 0;
}

struct fillctx { void *buf; fuse_fill_dir_t filler; int stop; };

static void synth_emit(void *ctx, const char *name, const char *full, enum tier t)
{
	struct fillctx *f = ctx;
	struct stat st;

	if (f->stop)
		return;
	memset(&st, 0, sizeof(st));
	if (SYNTHETIC(t)) {
		/* Its own fixed node, so `ls -l` of a synthetic tree agrees with
		 * a getattr of each child. */
		policy_synth_getattr(full, &st);
	}
	/* A pinned child's kind belongs to the filesystem that backs it and this
	 * listing has not asked; a zero mode is DT_UNKNOWN, which makes the
	 * caller stat the child and get the routed answer. */
	if (f->filler(f->buf, name, &st, 0, 0))
		f->stop = 1;
}

static int pt_readdir(const char *path, void *buf, fuse_fill_dir_t filler,
		      off_t off, struct fuse_file_info *fi,
		      enum fuse_readdir_flags flags)
{
	(void)off; (void)flags;
	struct dirhandle *h = (struct dirhandle *)(uintptr_t)fi->fh;
	struct dirent *de;

	if (!h->d) {
		struct fillctx fc = { buf, filler, 0 };
		struct stat st;

		memset(&st, 0, sizeof(st));
		policy_synth_getattr(h->path, &st);
		if (filler(buf, ".", &st, 0, 0) || filler(buf, "..", &st, 0, 0))
			return 0;
		policy_synth_children(h->path, synth_emit, &fc);
		return 0;
	}

	rewinddir(h->d);
	while ((de = readdir(h->d)) != NULL) {
		char  child[PATH_MAX];
		struct stat st;

		if (strcmp(de->d_name, ".") != 0 && strcmp(de->d_name, "..") != 0) {
			snprintf(child, sizeof(child), "%s%s%s",
				 strcmp(path, "/") == 0 ? "" : path, "/", de->d_name);
			/* the mountpoint and the union's own scaffolding. Without
			 * this the union lists its own backing store, and a
			 * dirent that cannot be stat'd is its own tell. */
			if (tier_of(child) == T_HIDE)
				continue;
		}
		memset(&st, 0, sizeof(st));
		st.st_ino  = de->d_ino;
		st.st_mode = de->d_type << 12;
		if (filler(buf, de->d_name, &st, 0, 0))
			break;
	}
	return 0;
}

static int pt_releasedir(const char *path, struct fuse_file_info *fi)
{
	struct dirhandle *h = (struct dirhandle *)(uintptr_t)fi->fh;
	(void)path;
	if (h->d) closedir(h->d);
	free(h);
	return 0;
}

