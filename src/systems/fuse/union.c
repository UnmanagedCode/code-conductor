static int pt_create(const char *path, mode_t mode, struct fuse_file_info *fi)
{
	ROUTE("create", path, CCU_FLAG_FOR_CREATE | CCU_FLAG_FOR_WRITE, CCU_FETCH);
	if ((rrc = policy_mutation_check(r.tier)) != 0) return rrc;
	cred_enter();
	int fd = openat(r.fd, rp, fi->flags | O_CREAT, mode);
	int e = errno;
	cred_leave();
	if (fd == -1) { abandon_claim(path, r.tier); return -e; }
	/* GATED LIKE THE FLOOR SITES, AND FOR A SHARPER REASON: `fd_view`'s ONLY
	 * reader is pt_getattr's fi arm, whose floor is a no-op today because
	 * libfuse passes `fi` to getattr only for regular files. An ungated
	 * route_view() here would pay a /proc mark read per open at `host`, the
	 * CLI's hottest tier, for a field nothing reads. Storing VIEW_CLI off the
	 * chain is harmless — policy_floor_applies cannot fire off the chain
	 * whatever the stored view says — so the two arms still agree
	 * STRUCTURALLY, which is the whole property that arm exists to keep. */
	fd_tier_set(fd, r.tier, 1,
		policy_cwd_component(path) ? route_view(&r) : VIEW_CLI);
	if (fd < FDTIER_SLOTS) fd_claimed[fd] = 1;
	fi->fh = fd;
	return 0;
}

static int pt_open(const char *path, struct fuse_file_info *fi)
{
	/* A WRITABLE HANDLE TAKES THE CLAIM, a read-only one does not: the claim
	 * turns cc's cache off for this path until the matching DIRTY, and a
	 * reader has no unpushed bytes to protect. */
	ROUTE("open", path, (fi->flags & (O_WRONLY | O_RDWR)) ? CCU_FLAG_FOR_WRITE : 0, CCU_FETCH);
	/* A directory is the only thing a synthetic node ever is. */
	if (SYNTHETIC(r.tier)) return -EISDIR;
	cred_enter();
	int fd = openat(r.fd, rp, fi->flags);
	int e = errno;
	cred_leave();
	if (fd == -1) {
		if (fi->flags & (O_WRONLY | O_RDWR)) abandon_claim(path, r.tier);
		return -e;
	}
	fd_tier_set(fd, r.tier, (fi->flags & (O_WRONLY | O_RDWR)) != 0,
		policy_cwd_component(path) ? route_view(&r) : VIEW_CLI);  /* gated; see pt_create */
	/* Exactly the handles whose ROUTE carried FOR_WRITE, so the claim cc took
	 * and the claim this daemon releases cannot disagree. */
	if (fd < FDTIER_SLOTS && (fi->flags & (O_WRONLY | O_RDWR)))
		fd_claimed[fd] = 1;
	fi->fh = fd;
	return 0;
}

/* read/write send no frame: the fd is already backed by a materialised file. */
static int pt_read(const char *path, char *buf, size_t size, off_t off,
		   struct fuse_file_info *fi)
{
	ssize_t n;
	(void)path;
	n = pread((int)fi->fh, buf, size, off);
	return n == -1 ? -errno : (int)n;
}

static int pt_write(const char *path, const char *buf, size_t size, off_t off,
		    struct fuse_file_info *fi)
{
	ssize_t n;
	(void)path;
	/* RE-ARM THE PUSH. `flush` clears the bit when its reconcile lands, and a
	 * handle written to again after that owes another one. */
	if ((int)fi->fh >= 0 && (int)fi->fh < FDTIER_SLOTS)
		fd_dirty[(int)fi->fh] = 1;
	n = pwrite((int)fi->fh, buf, size, off);
	return n == -1 ? -errno : (int)n;
}

static int pt_statfs(const char *path, struct statvfs *stbuf)
{
	ROUTE("statfs", path, 0, 0);
	(void)rp;
	/* `df /` must answer, and a synthetic node has no backing store of its
	 * own — for the MARKED CLI every tier but `host` is materialised into the
	 * mirror, so that is the filesystem whose free space it is actually
	 * consuming.
	 *
	 * AN UNMARKED CALLER IS ANSWERED FROM THE HOST, ALWAYS. Card 2026-0398
	 * gave it an overlay node at the cwd, which is a T_SYNTH route — and this
	 * body would have answered it with `fstatvfs(remote_fd)`, reaching into
	 * the mirror for a caller whose whole invariant is that it cannot.
	 *
	 * NO BYTES CROSS EITHER WAY, and that conclusion is unconditional: statvfs
	 * reports a filesystem's geometry and never a file's contents. WHETHER THE
	 * TWO ANSWERS AGREE IS CONDITIONAL and is recorded as a standing condition
	 * rather than asserted: the mirror is `<rundir>/mirror` under the store
	 * root and the host fd is an O_PATH on `/`, so the numbers coincide only
	 * where the store shares `/`'s filesystem. Put the store on its own mount
	 * and an unmarked `df` would have reported the store's free space for a
	 * path the caller is told is the orchestrator's — which is the second
	 * reason to route it here, and the one that survives a different disk
	 * layout.
	 *
	 * The first reason stands on its own: "an unmarked caller never reads the
	 * mirror" is a STRUCTURAL claim this file makes in its own header, and an
	 * op that reaches for `remote_fd` on its behalf falsifies it whatever the
	 * numbers say. */
	int fd = (r.tier == T_HOST || route_view(&r) == VIEW_HOST)
		? policy_host_fd : remote_fd;
	return fstatvfs(fd, stbuf) == -1 ? -errno : 0;
}

/*
 * THE PUSH LIVES IN `flush`, NOT IN `release`, AND THAT IS EPIC CRITERION 10.
 *
 * The kernel DISCARDS `release`'s return value — a reconcile that refused there
 * would be logged and nowhere else, and `close()` would return 0 to a worker
 * whose write never reached the system. `flush` is the op whose return value
 * `close(2)` reports, so that is where a failed reconcile has to be answered.
 * The worker sees the errno cc chose, which for a refused DIRTY is **EIO**.
 *
 * `flush` may fire more than once (each `close` of a duplicated descriptor
 * calls it), so the dirty bit is CLEARED by a successful push and SET AGAIN by
 * any later write: one reconcile per batch of writes, each answered to the
 * `close` that triggered it. `release` keeps a push as a backstop for the fd
 * that never saw a flush — a killed process — where there is no `close` left to
 * answer and landing the bytes is the whole of what is owed.
 */
static int pt_flush(const char *path, struct fuse_file_info *fi)
{
	int fd = (int)fi->fh;
	int rc;

	/* The dup/close first, unchanged: it is what reports a write error the
	 * kernel deferred, and it must be answered whatever the tier. */
	int probe = dup(fd);
	if (probe == -1) return -errno;
	if (close(probe) == -1) return -errno;

	if (fd < 0 || fd >= FDTIER_SLOTS || !fd_dirty[fd] ||
	    (enum tier)fd_tier[fd] != T_PROJECT)
		return 0;
	/* KEEPS THE CLAIM. `flush` fires per `close` of a duplicated descriptor
	 * while the original handle stays open, and releasing here left the next
	 * write batch on that handle unprotected — reopening exactly the window
	 * the claim exists to close. `release` is the only releaser. */
	rc = push_mirror_flags("flush", path, CCU_FLAG_FOR_WRITE);
	if (rc == 0)
		fd_dirty[fd] = 0;
	return rc;
}

/*
 * CRITERION 8'S SECOND HALF. A handle that was opened writable pushes DIRTY
 * before it closes, so cc copies the mirror's copy back to the source.
 *
 * READY MEANS CC HAS TAKEN OWNERSHIP OF THE PUSH, NOT THAT THE PUSH LANDED.
 * The awaiting half — a PostToolUse that blocks until it has, and poisons the
 * session if it has not — is 2026-0356's, deliberately (plan 2026-0355 §14).
 *
 * A file written through two handles pushes twice. The push is a full-content
 * copy, so that is idempotent; noted rather than defended against.
 */
static int pt_release(const char *path, struct fuse_file_info *fi)
{
	int fd = (int)fi->fh;

	/*
	 * THE ONLY RELEASER OF THE CLAIM, so this runs for a claimed handle
	 * whether or not anything is dirty — a `flush` that already pushed left
	 * the claim standing deliberately, and nothing else would ever drop it.
	 *
	 * AND IT NO LONGER RE-UPLOADS WHAT `flush` ALREADY LANDED. Against a
	 * local directory the second copy was cheap; against a real transport it
	 * is a second whole-file upload per written file, which is not a
	 * magnitude question (PROVENANCE D13d).
	 *
	 * THE KILLED-PROCESS BACKSTOP IS PRESERVED BY THE CONDITION ITSELF, not
	 * by a second test bolted beside it. A handle whose `flush` never ran —
	 * or whose `flush` refused — still has fd_dirty set, so it sends a FULL
	 * reconcile, which is the whole of what is owed when there is no
	 * `close(2)` left to answer.
	 */
	if (fd >= 0 && fd < FDTIER_SLOTS && fd_claimed[fd] &&
	    (enum tier)fd_tier[fd] == T_PROJECT) {
		push_mirror_flags("release", path,
				  fd_dirty[fd] ? 0 : CCU_FLAG_RELEASE_ONLY);
	}
	if (fd >= 0 && fd < FDTIER_SLOTS) {
		fd_tier[fd] = 0;
		fd_dirty[fd] = 0;
		fd_claimed[fd] = 0;
	}
	close(fd);
	return 0;
}

static int pt_fsync(const char *path, int datasync, struct fuse_file_info *fi)
{
	(void)path;
	int rc = datasync ? fdatasync((int)fi->fh) : fsync((int)fi->fh);
	return rc == -1 ? -errno : 0;
}

static int pt_fallocate(const char *path, int mode, off_t off, off_t len,
			struct fuse_file_info *fi)
{
	(void)path;
	if (fallocate((int)fi->fh, mode, off, len) == -1)
		return -errno;
	/* CONTENT CHANGED, so the handle owes a push. FALLOC_FL_ZERO_RANGE and
	 * FALLOC_FL_PUNCH_HOLE rewrite bytes and a plain fallocate extends the
	 * file, and `flush` clears the bit on a successful reconcile — without
	 * this, `write; flush; fallocate; close` reconciled the pre-fallocate
	 * content and the size change never reached the system. */
	fd_mark_dirty(fi->fh);
	return 0;
}

static off_t pt_lseek(const char *path, off_t off, int whence,
		      struct fuse_file_info *fi)
{
	(void)path;
	off_t rc = lseek((int)fi->fh, off, whence);
	return rc == -1 ? -errno : rc;
}

/* xattr: reported through the routed tier, so a caller that consults them sees
 * the real answer of the tier that owns the file rather than a synthetic
 * ENOTSUP -- and never the other tier's. A synthetic node has no xattrs of its
 * own and must not borrow the host directory's.
 *
 * THE TWO THAT MUTATE ROUTE WITH `FETCH`, NOT `STAT`, and that is not
 * symmetry for its own sake: `FETCH` is where the resolution cache is
 * invalidated, and the rule "every op that can change a file passes that
 * point" is asserted as an ENUMERATION. `setxattr` and `removexattr` read like
 * metadata queries and change the file; `getxattr` and `listxattr` do not. */
static void abspath(const struct route *r, const char *path, char *out, size_t n)
{
	const char *root = (r->fd == remote_fd) ? remote_root : host_root;
	snprintf(out, n, "%s%s", strcmp(root, "/") == 0 ? "" : root, path);
}

static int pt_setxattr(const char *path, const char *name, const char *value,
		       size_t size, int flags)
{
	ROUTE("setxattr", path, CCU_FLAG_FOR_WRITE, CCU_FETCH);
	(void)rp;
	if (SYNTHETIC(r.tier)) return -EOPNOTSUPP;
	if ((rrc = refuse_unreconcilable("setxattr", path, r.tier)) != 0) { abandon_claim(path, r.tier); return rrc; }
	char abs[PATH_MAX];
	abspath(&r, path, abs, sizeof(abs));
	return lsetxattr(abs, name, value, size, flags) == -1 ? -errno : 0;
}

static int pt_getxattr(const char *path, const char *name, char *value, size_t size)
{
	ROUTE("getxattr", path, 0, CCU_STAT);
	(void)rp;
	/* THE READS REFUSE TOO, and for the mirror's sake rather than the
	 * reconcile's: cc materialises a project path with `copyFile`, which
	 * carries no extended attributes, so the mirror entry has NONE of the
	 * source's. Answering from it would report "no such attribute" about a
	 * file that has one — one path, two answers, in the direction a caller
	 * cannot detect. EOPNOTSUPP is a filesystem's ordinary answer here. */
	if ((rrc = policy_unreconcilable(r.tier))) return rrc;
	if (SYNTHETIC(r.tier)) return -EOPNOTSUPP;
	char abs[PATH_MAX];
	abspath(&r, path, abs, sizeof(abs));
	ssize_t n = lgetxattr(abs, name, value, size);
	return n == -1 ? -errno : (int)n;
}

static int pt_listxattr(const char *path, char *list, size_t size)
{
	ROUTE("listxattr", path, 0, CCU_STAT);
	(void)rp;
	if ((rrc = policy_unreconcilable(r.tier))) return rrc;
	if (SYNTHETIC(r.tier)) return -EOPNOTSUPP;
	char abs[PATH_MAX];
	abspath(&r, path, abs, sizeof(abs));
	ssize_t n = llistxattr(abs, list, size);
	return n == -1 ? -errno : (int)n;
}

static int pt_removexattr(const char *path, const char *name)
{
	ROUTE("removexattr", path, CCU_FLAG_FOR_WRITE, CCU_FETCH);
	(void)rp;
	if (SYNTHETIC(r.tier)) return -EOPNOTSUPP;
	if ((rrc = refuse_unreconcilable("removexattr", path, r.tier)) != 0) { abandon_claim(path, r.tier); return rrc; }
	char abs[PATH_MAX];
	abspath(&r, path, abs, sizeof(abs));
	return lremovexattr(abs, name) == -1 ? -errno : 0;
}

