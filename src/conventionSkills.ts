// On-disk material for convention skill parts: each session's generated Claude
// Code plugin roots, one per namespace, loaded with `--plugin-dir`.
//
// The split itself (inline part vs skill part) is src/fragmentCatalog.ts's
// splitSkillPart; the scope composers return both parts off one selection read.
// This module only writes what they returned and reclaims it. Layout, lifecycle
// and namespaces: docs/architecture.md → "Convention skill parts".

import { promises as fsp, rmSync } from 'node:fs';
import path from 'node:path';
import { orchStoreRoot } from './projects.ts';
import type { ConventionSkill } from './fragmentCatalog.ts';
import type { ConventionScope } from './conventionsDir.ts';

const ROOT_DIRNAME = 'convention-skills';

// One instance's skill dir. Fixed at create (InstanceManager._doCreateResolved
// freezes it on the Instance); its CONTENT is rewritten on every launch.
export function conventionSkillsDir(instanceId: string): string {
  return path.join(orchStoreRoot(), ROOT_DIRNAME, instanceId);
}

export interface ScopeSkills {
  scope: ConventionScope;
  skills: ConventionSkill[];
}

// The Claude Code plugin name a skill is delivered under: `cc-<scope>` for a
// built-in or core, `cc-<scope>-<plugin-id>` for a plugin's. A skill is invoked
// as `<namespace>:<name>`.
export function skillNamespace(scope: ConventionScope, plugin?: string): string {
  return plugin ? `cc-${scope}-${plugin}` : `cc-${scope}`;
}

// Replace `dir` with one plugin root per non-empty namespace and return the
// roots in `--plugin-dir` order: every group's built-in root (group order),
// then each plugin's root (first-appearance order). Writes nothing, and returns
// [], when no group carries a skill — a session with no skill part in force
// gets the argv it would have had without this feature.
export async function writeConventionSkills(dir: string, groups: ScopeSkills[]): Promise<string[]> {
  await fsp.rm(dir, { recursive: true, force: true });
  const builtins = new Map<string, ConventionSkill[]>();
  const plugins = new Map<string, ConventionSkill[]>();
  for (const { scope, skills } of groups) {
    for (const s of skills) {
      const into = s.plugin ? plugins : builtins;
      const ns = skillNamespace(scope, s.plugin);
      const list = into.get(ns) ?? [];
      // A repeated name inside one namespace would be one skill dir written
      // twice; the composers already deliver each slug once.
      if (!list.some(x => x.name === s.name)) list.push(s);
      into.set(ns, list);
    }
  }
  const roots: string[] = [];
  for (const [ns, skills] of [...builtins, ...plugins]) {
    const root = path.join(dir, ns);
    await fsp.mkdir(path.join(root, '.claude-plugin'), { recursive: true });
    await fsp.writeFile(path.join(root, '.claude-plugin', 'plugin.json'),
      JSON.stringify({ name: ns, description: 'Convention skills generated by code-conductor.' }, null, 2) + '\n');
    for (const s of skills) {
      const skillDir = path.join(root, 'skills', s.name);
      await fsp.mkdir(skillDir, { recursive: true });
      await fsp.writeFile(path.join(skillDir, 'SKILL.md'), renderSkill(s));
    }
    roots.push(root);
  }
  return roots;
}

// The description is a JSON string, which is a valid YAML double-quoted scalar,
// so no description text can break the frontmatter.
export function renderSkill(s: ConventionSkill): string {
  return `---\nname: ${s.name}\ndescription: ${JSON.stringify(s.description)}\n---\n\n${s.body}\n`;
}

// Teardown for one instance (remove / removeAllForProject / shutdown).
export function removeConventionSkills(dir: string): void {
  rmSync(dir, { recursive: true, force: true });
}

// Reclaim every instance skill dir no live session owns — the boot sweep, for
// the same reason sweepSessionTmpDirs (src/instances.ts) exists: a killed
// orchestrator runs no teardown, and an instance id is never reused across
// processes. Best-effort: a dir cc cannot remove never stops a boot.
export async function sweepConventionSkillDirs(liveIds: Iterable<string>): Promise<void> {
  const keep = new Set(liveIds);
  const root = path.join(orchStoreRoot(), ROOT_DIRNAME);
  let entries: string[];
  try { entries = await fsp.readdir(root); }
  catch { return; }
  for (const name of entries) {
    if (keep.has(name)) continue;
    try { await fsp.rm(path.join(root, name), { recursive: true, force: true }); }
    catch (e) { console.warn(`conventionSkills: could not reclaim ${path.join(root, name)}: ${(e as Error).message}`); }
  }
}
