// list_sessions / describe_session render a session's first prompt the way a
// label shows it (public/promptPreview.ts readablePrompt): a prompt the server
// or the CLI wrote reads by name, a person's reads as typed.
//
// Each first prompt is built by its real producer, written as a transcript and
// read back through readFirstPrompt, so the text rendered is the stored head the
// server keeps — cut BEFORE it is cleaned. Every kind is checked on each surface
// that prints it: the LIVE block's `first` and the inactive line's title column,
// in both tools.

import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { renderSessions, renderSession } from '../src/mcp/readRenderers.ts';
import { readFirstPrompt } from '../src/projects.ts';
import { buildWakeStub, WAKE_BODY_SEP } from '../shared/wakeCallback.ts';
import { readablePrompt } from '../shared/promptPreview.ts';
import { backgroundJobsNote } from '../src/backgroundJobs.ts';
import { buildForwardFrame } from '../shared/forwardFrame.ts';
import { buildRenewSeed } from '../shared/renewSeed.ts';

const SID = '3f2a8c11-77b2-4c1e-9a2f-5d6e7f801234';
const WORKER = '7c0e5a2d-41b8-4f3a-9d26-b1e8f0c43a17';

let dir;
before(async () => { dir = await fs.mkdtemp(path.join(os.tmpdir(), 'cc-first-prompt-render-')); });
after(async () => { await fs.rm(dir, { recursive: true, force: true }); });

// The CLI's user record for a prompt cc sent, content as text blocks.
const userTurn = text => ({ type: 'user', message: { role: 'user', content: [{ type: 'text', text }] } });

// The head a renewed segment's file opens with, as the CLI writes it after
// renew_session's `/clear` (shape captured from a real renewed segment).
const CLEAR_HEAD = [
  { type: 'mode', mode: 'default', sessionId: SID },
  { type: 'user', isMeta: true, message: { role: 'user', content: '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>' } },
  { type: 'user', message: { role: 'user', content: '<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>' } },
  { type: 'queue-operation', operation: 'enqueue', sessionId: SID },
  { type: 'queue-operation', operation: 'dequeue', sessionId: SID },
];

// The stored first prompt of a transcript holding `records`.
async function storedFirstPrompt(name, records) {
  const file = path.join(dir, `${name}.jsonl`);
  await fs.writeFile(file, records.map(r => JSON.stringify(r)).join('\n') + '\n');
  return readFirstPrompt(file);
}

const liveRow = firstPrompt => ({ sessionId: SID, title: null, firstPrompt });
const stoppedRow = firstPrompt => ({
  sessionId: SID, title: null, firstPrompt, conducted: false, temp: false, archived: false,
  lastActivity: 1786001000000, playbook: null, stage: null, resumeMode: 'plan',
});
const group = over => ({
  project: 'p', worktree: null, path: '/p', branch: 'main', mergeStatus: null,
  live: [], inactive: [], archivedCount: 0, ...over,
});

// The line carrying the first prompt on each surface.
const titleLine = out => out.split('\n').find(l => /^ +title /.test(l)).trim();
const sessionLine = out => out.split('\n').find(l => l.trimStart().startsWith(SID)).trim().replace(/ {2,}/g, '  ');

const SURFACES = {
  'list_sessions LIVE row': fp => titleLine(renderSessions([group({ live: [liveRow(fp)] })])),
  'describe_session live': fp => titleLine(renderSession({ sessionId: SID, live: liveRow(fp) })),
  'list_sessions inactive row': fp => sessionLine(renderSessions([group({ inactive: [stoppedRow(fp)] })])),
  'describe_session retired': fp => sessionLine(renderSession({
    sessionId: SID, project: 'p', worktree: null, path: '/p', retired: stoppedRow(fp),
  })),
};

// `live` is the LIVE block's title line, `inactive` the session line's text.
async function expectOnEverySurface(t, records, { live, inactive }) {
  const fp = await storedFirstPrompt(t.name.replace(/\W+/g, '-'), records);
  for (const [surface, render] of Object.entries(SURFACES)) {
    await t.test(surface, () => {
      const want = surface.endsWith('live') || surface.endsWith('LIVE row')
        ? live
        : `${SID}  2026-08-06 07:23Z  —  —  ${inactive}`;
      assert.equal(render(fp), want);
    });
  }
}

test('a wake-callback first prompt renders as Wake: <summary>, never the [[cc: marker', async t => {
  await expectOnEverySurface(t, [userTurn(buildWakeStub({ targetSessionId: WORKER, payloadText: 'Done: 3 files changed.' }))], {
    live: `title —   first Wake: Worker \`${WORKER}\` finished its turn. Its recent output is folded …`,
    inactive: `Wake: Worker \`${WORKER}\` finishe…`,
  });
});

// The store cut never reaches a wake stub's body separator: for every stub
// buildWakeStub produces, WAKE_BODY_SEP starts at or past the end of the head
// readFirstPrompt keeps, so no part of it — not even its leading `\n` — is in
// the head, and the head reads, in full and untruncated, as the summary alone.
// The cut is measured off readFirstPrompt's own output (its 200-char slice in
// src/projects.ts exports no constant). A note only prefixes the summary and a
// jobs note only suffixes it, so the bare stub is the binding case.
test('the stored head of every wake stub stops before its body separator', async t => {
  const NOW = 1786001000000;
  const notes = { 'no note': null, 'a note': 'NOTE: the renewal was declined.' };
  const jobsNotes = {
    'no jobs': null,
    'one job': backgroundJobsNote(WORKER, [{ title: 'npm test', startedAt: NOW - 60_000 }], NOW),
    'two jobs': backgroundJobsNote(WORKER, [
      { title: 'npm test', startedAt: NOW - 60_000 },
      { title: 'tail -f server.log', startedAt: NOW - 5_000 },
    ], NOW),
  };
  for (const [noteName, note] of Object.entries(notes)) {
    for (const [jobsName, jobsNote] of Object.entries(jobsNotes)) {
      const name = `${noteName}, ${jobsName}`;
      await t.test(name, async () => {
        const raw = buildWakeStub({ targetSessionId: WORKER, payloadText: 'Done: 3 files changed.', note, jobsNote });
        const stored = await storedFirstPrompt(`wake-head-${name.replace(/\W+/g, '-')}`, [userTurn(raw)]);
        assert.ok(stored.length < raw.length && raw.startsWith(stored),
          `the stored head is a cut prefix of the stub (${stored.length} of ${raw.length} chars)`);
        assert.ok(raw.indexOf(WAKE_BODY_SEP) >= stored.length,
          `the separator starts at ${raw.indexOf(WAKE_BODY_SEP)}, inside the ${stored.length}-char head`);
        const readable = readablePrompt(stored);
        assert.ok(readable.startsWith('Wake: '), readable);
        assert.ok(!readable.includes('[[cc:'), readable);
      });
    }
  }
});

test('a forwarded-frame first prompt renders as Forwarded worker output', async t => {
  await expectOnEverySurface(t, [userTurn(buildForwardFrame({
    messages: ['The migration is written and its test is green.'],
    instruction: 'Review the migration.',
  }))], {
    live: 'title —   first Forwarded worker output',
    inactive: 'Forwarded worker output',
  });
});

test('a renew_session seed first prompt renders as Context renewed', async t => {
  await expectOnEverySurface(t, [userTurn(buildRenewSeed({ summary: 'Implementing the migration; tests next.' }))], {
    live: 'title —   first Context renewed',
    inactive: 'Context renewed',
  });
});

test('a renewed segment whose file opens with the CLI\'s /clear head renders as Context renewed', async t => {
  // readFirstPrompt stops at the caveat record, ahead of the seed; it must name
  // the renewal exactly as the seed itself would.
  await expectOnEverySurface(t, [...CLEAR_HEAD, userTurn(buildRenewSeed({ summary: 'Implementing the migration.' }))], {
    live: 'title —   first Context renewed',
    inactive: 'Context renewed',
  });
});

test('a human first prompt renders unchanged, even one quoting a [[cc: marker', async t => {
  await expectOnEverySurface(t, [userTurn(
    '**Card 2026-0641: the /next/ sidebar session label shows a raw `[[cc:wake-callback]]` stub when that is the session\'s first prompt.** You plan it and then implement it (solo playbook).',
  )], {
    live: 'title —   first **Card 2026-0641: the /next/ sidebar session label shows a raw `[[cc:wake-callback]]` stub when tha…',
    inactive: '**Card 2026-0641: the /next/ sidebar session label shows a …',
  });
});
