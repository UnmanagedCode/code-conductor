test('worktrees, reads, diff and bash', async () => {
  await ok('create_worktree', { project: 'demo', name: 'job' });
  const { worktrees } = await ok('list_worktrees', { project: 'demo' });
  const job = worktrees.find(w => w.worktree === 'job');
  await fs.writeFile(path.join(job.worktreePath, 'feature.txt'), 'feature\n');
  await git(job.worktreePath, 'add', '.');
  await git(job.worktreePath, 'commit', '-q', '-m', 'feature');
  await fs.writeFile(path.join(job.worktreePath, 'untracked.txt'), 'u\n');

  await ok('project_status', { project: 'demo' });
  await ok('project_status', { project: 'demo', worktree: 'job' });
  await fs.writeFile(path.join(repoPath, 'blob.bin'), Buffer.from([0, 1, 2, 3]));
  const fast = await ok('project_read', { project: 'demo', relativePath: 'README.md' });
  assert.equal(fast.body, '# demo\nline two\n');
  const lines = await ok('project_read', { project: 'demo', relativePath: 'README.md', offset: 2, limit: 1, lineNumbers: true });
  assert.equal(lines.startLine, 2);
  const bin = await ok('project_read', { project: 'demo', relativePath: 'blob.bin' });
  assert.equal(bin.encoding, 'base64');
  await fs.rm(path.join(repoPath, 'blob.bin'));
  const diff = await ok('project_diff', { project: 'demo', worktree: 'job' });
  assert.match(diff.body, /feature\.txt/);
  const summary = await ok('project_diff', { project: 'demo', worktree: 'job', summary: true });
  assert.equal(summary.totals.files, 1);
  // The workers run in-process, so CLAUDE_BIN only reaches the bundle spawn.
  const prevBin = process.env.CLAUDE_BIN;
  process.env.CLAUDE_BIN = `${process.execPath} ${fakeShellEnvBin}`;
  let bash;
  try {
    bash = await ok('project_bash', { project: 'demo', command: 'echo hi', description: 'Say hi' });
  } finally {
    process.env.CLAUDE_BIN = prevBin;
  }
  assert.equal(bash.output, 'hi');
  assert.equal(bash.exitCode, 0);
});

