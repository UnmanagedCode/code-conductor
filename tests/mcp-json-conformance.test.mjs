test('renewal, prune and kill', async () => {
  // Targeted: ask an idle worker to renew itself.
  const w2 = await spawnRest('demo');
  const asked = await ok('renew_session', { sessionId: w2 }, { caller: callerSid });
  assert.equal(asked.requested, true);
  // Bare: the caller renews itself.
  const self = await ok('renew_session', { summary: 'handoff' }, { caller: callerSid });
  assert.equal(self.willClearAtTurnEnd, true);

  const sid = 'cccccccc-2222-3333-4444-555555555555';
  await api(srv.baseUrl, 'POST', '/api/projects', { name: 'prunee' });
  const dir = path.join(srv.claudeProjectsRoot, encodeCwd(path.join(srv.projectsRoot, 'prunee')));
  await fs.mkdir(dir, { recursive: true });
  await fs.writeFile(path.join(dir, `${sid}.jsonl`), seededTurns().map(l => JSON.stringify(l)).join('\n') + '\n');
  const r = await api(srv.baseUrl, 'POST', '/api/instances', { project: 'prunee', mode: 'bypassPermissions', resume: sid });
  assert.equal(r.status, 201, JSON.stringify(r.body));
  await idle(sid);
  const pruned = await ok('prune_session', { sessionId: sid });
  assert.equal(pruned.ok, true);

  await ok('kill_instance', { sessionId: worker });

  // A retired session: the pruned worker, killed, leaves its transcript — the
  // retired arm of describe_session and an inactive list_sessions row. A second
  // seeded transcript, archived, makes the group's archivedCount real.
  await ok('kill_instance', { sessionId: sid });
  await waitFor(() => !instForSession(srv.instances, sid)?.proc);
  const archivedSid = 'dddddddd-2222-3333-4444-555555555555';
  await fs.writeFile(path.join(dir, `${archivedSid}.jsonl`), seededTurns().map(l => JSON.stringify(l)).join('\n') + '\n');
  assert.equal(await archiveSessionForCwd(localPlace(path.join(srv.projectsRoot, 'prunee')), archivedSid), true, 'precondition: archived');
  const retired = await ok('describe_session', { sessionId: sid });
  assert.ok(retired.retired, `the retired arm: ${JSON.stringify(retired)}`);
  const { groups } = await ok('list_sessions', { project: 'prunee' });
  const group = groups.find(g => g.worktree === null);
  assert.ok(group.inactive.some(r => r.sessionId === sid), 'the retired session is an inactive row');
  assert.ok(group.archivedCount > 0, 'the archived transcript is counted');
});

