// The JSON-format contract (docs/mcp-applications.md), driven tool by tool.
//
// Every core tool is called through /mcp?format=json against a live fixture —
// a real git project with a worktree, fake-CLI workers, a conductor, a
// reference-provider System — and each success is checked against the tool's
// outputSchema from the JSON tools/list, with `content` exactly one text block
// holding JSON.stringify(structuredContent). Schemas are CLOSED, so a handler
// that grows a field fails here until its schema learns it.
//
// The closing tests pin completeness: the driven set IS the capability-filtered
// registry (a tool with no driver fails), every listed tool carries an
// outputSchema inside the validated subset (tests/jsonSchemaSubset.mjs), and
// refusals, faults and bridged plugin tools take their documented channels.
