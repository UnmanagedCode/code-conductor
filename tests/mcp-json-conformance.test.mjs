// ---------- refusals, faults, pass-through ----------

test('refusals are isError:true with the refusal schema, whatever their source', async () => {
  // A handler soft refusal.
  await refused('send_prompt', { sessionId: 'deadbeef-0000-4000-8000-000000000000', text: 'x' }, 'SESSION_UNKNOWN');
  // A thrown 404: the same code the text view's error block carries, plus the status.
  const nf = await refused('project_read', { project: 'demo', relativePath: 'nope.txt' }, 'NOT_FOUND');
  assert.equal(nf.statusCode, 404);
  // A thrown error with neither code nor status.
  await refused('describe_session', { sessionId: '' }, 'TOOL_ERROR');
  // The playbook gate, before any handler: an enforcing conductor's bare spawn.
  await refused('spawn_instance', { project: 'demo', mode: 'bypassPermissions' }, 'PLAYBOOK_UNKNOWN', { caller: conductorSid });
  // A handler refusal with no code of its own is REFUSED: sync_worktree whose
  // base branch is gone cannot compare.
  await ok('create_worktree', { project: 'demo', name: 'orphan' });
  await git(repoPath, 'branch', '-m', 'main', 'trunk');
  const codeless = await refused('sync_worktree', { project: 'demo', worktree: 'orphan' }, 'REFUSED');
  assert.equal(typeof codeless.reason, 'string');
});

test('faults are JSON-RPC errors carrying the refusal shape', async () => {
  const unknown = await rpc('tools/call', { name: 'no_such_tool', arguments: {} });
  assert.equal(unknown.error.code, -32602);
  assert.equal(unknown.error.data.code, 'TOOL_UNKNOWN');
  assert.equal(unknown.error.data.ok, false);
  const bad = await rpc('tools/call', { name: 'list_worktrees', arguments: { project: 'demo', bogus: 1 } });
  assert.equal(bad.error.code, -32602);
  assert.equal(bad.error.data.code, 'ARGS_INVALID');
  const method = await rpc('no/such/method', {});
  assert.equal(method.error.data.code, 'METHOD_UNKNOWN');
});

test('a bridged plugin tool passes through untouched, in both formats', async () => {
  const router = buildMcpRouter({
    instances: null,
    pluginHost: { init: async () => {}, toolsFor: () => [{
      name: 'plug__echo', description: 'echo', inputSchema: { type: 'object' },
      handler: async () => ({ hello: 'world' }),
    }] },
    playbookGate: { check: async ({ args }) => ({ args }) },
  });
  const app = express();
  app.use('/mcp', router);
  const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
  try {
    for (const format of ['json', 'text']) {
      const res = await fetch(`http://127.0.0.1:${server.address().port}/mcp?format=${format}`, {
        method: 'POST', headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name: 'plug__echo', arguments: {} } }),
      });
      const { result } = await res.json();
      assert.deepEqual(result, { content: [{ type: 'text', text: '{"hello":"world"}' }] }, format);
    }
  } finally {
    await new Promise(resolve => server.close(resolve));
  }
});

