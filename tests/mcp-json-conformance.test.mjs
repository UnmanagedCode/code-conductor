test('every core tool was driven, and every listed tool has a valid outputSchema', () => {
  const expected = buildTools(JSON_LIMITS)
    .filter(t => !t.requires || hostPlatform.capabilities[t.requires])
    .map(t => t.name).sort();
  assert.deepEqual([...driven].sort(), expected, 'a core tool has no driver here');
  for (const [name, schema] of schemas) {
    assert.ok(schema, `${name} lists no outputSchema`);
    assert.doesNotThrow(() => checkSchema(schema), `${name}'s outputSchema leaves the validated subset`);
    assert.equal(schema.type, 'object', `${name}: an outputSchema is an object schema`);
  }
  checkSchema(REFUSAL_SCHEMA);
});
