const driven = new Set();
let nextId = 1;

async function rpc(method, params, { caller = null, format = 'json' } = {}) {
  const res = await fetch(mcpUrl(srv.baseUrl, { caller, format }), {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ jsonrpc: '2.0', id: nextId++, method, params }),
  });
  return res.json();
}

// One JSON-format tools/call that must SUCCEED: its structuredContent validates
// against the tool's outputSchema and content is its one JSON text block.
async function ok(name, args, opts) {
  const body = await rpc('tools/call', { name, arguments: args }, opts);
  assert.ok(body.result, `${name}: no result — ${JSON.stringify(body).slice(0, 500)}`);
  const r = body.result;
  assert.notEqual(r.isError, true, `${name} refused: ${JSON.stringify(r.structuredContent).slice(0, 800)}`);
  assert.ok(r.structuredContent && typeof r.structuredContent === 'object', `${name}: no structuredContent`);
  assert.deepEqual(r.content, [{ type: 'text', text: JSON.stringify(r.structuredContent) }], `${name}: content`);
  const errors = validate(schemas.get(name), r.structuredContent);
  assert.deepEqual(errors, [], `${name} does not match its outputSchema: ${JSON.stringify(r.structuredContent).slice(0, 1500)}`);
  // Covered only once its JSON has actually been validated.
  driven.add(name);
  return r.structuredContent;
}

// One JSON-format tools/call that must be REFUSED as a structured refusal.
async function refused(name, args, code, opts) {
  const body = await rpc('tools/call', { name, arguments: args }, opts);
  const r = body.result;
  assert.ok(r, `${name}: no result — ${JSON.stringify(body)}`);
  assert.equal(r.isError, true, `${name} was not refused: ${JSON.stringify(r).slice(0, 500)}`);
  assert.deepEqual(r.content, [{ type: 'text', text: JSON.stringify(r.structuredContent) }]);
  assert.deepEqual(validate(REFUSAL_SCHEMA, r.structuredContent), []);
  assert.equal(r.structuredContent.code, code, JSON.stringify(r.structuredContent));
  return r.structuredContent;
}

async function spawnRest(project, extra = {}) {
  const r = await api(srv.baseUrl, 'POST', '/api/instances', { project, mode: 'bypassPermissions', ...extra });
  assert.equal(r.status, 201, JSON.stringify(r.body));
  await waitFor(() => instForSession(srv.instances, r.body.sessionId)?.status === 'idle');
  return r.body.sessionId;
}

async function idle(sid) {
  await waitFor(() => instForSession(srv.instances, sid)?.status === 'idle', { timeout: 15000 });
}

async function makeRealRepo(name) {
  const dir = path.join(srv.projectsRoot, name);
  await registerLocalProject(name, dir);
  await git(dir, 'init', '-q', '-b', 'main');
  await git(dir, 'config', 'user.email', 'test@example.com');
  await git(dir, 'config', 'user.name', 'test');
  await git(dir, 'config', 'commit.gpgsign', 'false');
  await fs.writeFile(path.join(dir, 'README.md'), '# demo\nline two\n');
  await git(dir, 'add', '.');
  await git(dir, 'commit', '-q', '-m', 'initial');
  return dir;
}

